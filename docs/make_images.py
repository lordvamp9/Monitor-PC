"""Compose documentation images from a real --capture BMP; requires Pillow.
Run from the repository root after exporting dist/overlay-capture.bmp.
No metrics or graphs are generated by this script.
"""
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont
import math

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs/images"
OUT.mkdir(parents=True, exist_ok=True)
capture = Image.open(ROOT / "dist/overlay-capture.bmp").convert("RGBA")
pixels = capture.load()
for y in range(capture.height):
    for x in range(capture.width):
        r, g, b, _ = pixels[x, y]
        if r == 255 and g == 0 and b == 255:
            pixels[x, y] = (0, 0, 0, 0)
        else:
            pixels[x, y] = (r, g, b, 255)
font_root = Path("C:/Windows/Fonts")
def font(size, bold=False):
    return ImageFont.truetype(str(font_root / ("segoeuib.ttf" if bold else "segoeui.ttf")), size)

def background(w, h):
    image = Image.new("RGB", (w, h))
    px = image.load()
    for y in range(h):
        for x in range(w):
            cyan = math.exp(-(((x-w*.80)/(w*.4))**2 + ((y-h*.2)/(h*.7))**2)*3)
            green = math.exp(-(((x-w*.65)/(w*.5))**2 + ((y-h*.90)/(h*.5))**2)*3)
            px[x, y] = (int(7+2*cyan), int(12+24*cyan+11*green), int(22+34*cyan+7*green))
    return image.convert("RGBA")

overlay = background(900, 760)
overlay.alpha_composite(capture.resize((900, 760), Image.Resampling.LANCZOS))
overlay.convert("RGB").save(OUT / "overlay.png", optimize=True)

hero = background(1600, 900)
d = ImageDraw.Draw(hero)
d.text((90, 82), "MONITOR PC", font=font(27, True), fill="#00c8ff")
d.text((90, 195), "Know your", font=font(83, True), fill="#f2f6fc")
d.text((90, 290), "hardware.", font=font(83, True), fill="#f2f6fc")
d.text((94, 430), "A clean overlay. Real telemetry.", font=font(29), fill="#b4c4d8")
for y, label, color in [(535, "Native C++17 + Win32", "#00c8ff"), (592, "CPU / GPU / RAM / FPS", "#00ff64"), (649, "No simulated readings", "#ff7896")]:
    d.ellipse((96, y+12, 106, y+22), fill=color)
    d.text((126, y), label, font=font(25), fill="#dce7f5")
d.rounded_rectangle((830, 117, 1510, 768), radius=26, fill="#0b1422", outline="#274457", width=2)
d.text((861, 142), "LIVE OVERLAY / ACTUAL APP CAPTURE", font=font(17, True), fill="#7d98ae")
hero.alpha_composite(capture.resize((630, 532), Image.Resampling.LANCZOS), (851, 201))
d.text((94, 823), "WINDOWS 10/11  /  NVIDIA - AMD - INTEL PROVIDERS", font=font(18), fill="#7891a6")
d.text((860, 804), "Unavailable sensors are shown as N/A.", font=font(18), fill="#7891a6")
hero.convert("RGB").save(OUT / "hero.png", optimize=True)
print("Created hero.png and overlay.png from the real app render.")
